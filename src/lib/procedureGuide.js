/** 유형 × 단계 → 그 자리에서 필요한 모든 것 */
export function stageGuide(typeKey, stageKey) {
  const base = BASE[stageKey] || BASE.deal
  const over = BY_TYPE[typeKey]?.[stageKey] || {}
  return { ...base, ...over }
}

