/** 기한을 사람이 읽는 한 줄로 */
export function deadlineSpan(d) {
  if (d.years) return `${d.years}년`
  if (d.weeks) return `${d.weeks}주`
  if (typeof d.days === 'number' && d.days !== 0) return d.days < 0 ? `${-d.days}일 전까지` : `${d.days}일`
  // 「이사하기 전」·「2기 연체」처럼 날짜가 아니라 조건으로 정해지는 기한
  return '조건으로 정해짐'
}
