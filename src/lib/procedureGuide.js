// 절차 안내 — 단계마다 무엇을 하고, 무엇을 챙기고, 언제까지인가.
//
// ── 왜 한 파일에 모으는가 ──────────────────────────────────────
// 예전에는 설명(GUIDE)·준비물(MATERIALS)·기한(DEADLINES)이 화면 파일 안에 따로 흩어져
// 있었고, 기한은 사건 유형과 무관하게 세 단계에만 붙어 있었다. 그러다 보니
// 대여금 사건에서 「임대차계약서를 챙기세요」가 뜨고, 임금 사건인데 3년 시효가
// 어디에도 안 보였다.
//
// 절차 지식은 **유형 × 단계**의 표다. 표는 표로 두는 편이 고치기 쉽다.
//
// ── 쓰는 법 ───────────────────────────────────────────────────
//   stageGuide('loan', 'draft') → { desc, items, materials, deadlines, tools }
// 유형별로 적어 둔 것이 있으면 그것을, 없으면 BASE를 쓴다. 한 단계 안에서 키 단위로
// 덮어쓰므로, 유형에서 `materials`만 적으면 설명·기한은 BASE 것이 그대로 남는다.
//
// ── 근거 ──────────────────────────────────────────────────────
//   답변서 30일        민사소송법 제256조 제1항
//   항소 2주           민사소송법 제396조 제1항 (불변기간)
//   지급명령 이의 2주   민사소송법 제470조 제1항 (불변기간)
//   이행권고 이의 2주   소액사건심판법 제5조의4 제1항 (불변기간)
//   채권 소멸시효 10년  민법 제162조 제1항
//   불법행위 3년/10년   민법 제766조
//   임금채권 3년        근로기준법 제49조 · 퇴직금 3년 근로자퇴직급여 보장법 제10조
//   금품청산 14일       근로기준법 제36조
//   차임 2기 연체 해지  민법 제640조 (상가는 3기 — 상가건물 임대차보호법 제10조의8)

