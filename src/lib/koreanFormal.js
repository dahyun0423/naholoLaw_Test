// 평소 말투를 서면 문장으로 다듬는다.
//
// 사용자는 「아니 근데 막 전화를 안 받아요...」처럼 적는다. 그대로 소장에 실으면
// 그 문장이 법원에 간다. 그래서 문서로 나가기 전에 세 가지를 손본다.
//
//   ① 군더더기 — 「아니」·「근데」·「막」·「진짜」 같은 말버릇과 「...」·「!!」
//   ② 맞춤법  — 「바램」·「되요」·「몇일」처럼 자주 틀리는 것
//   ③ 말투    — 구어 낱말을 서면 낱말로, 해요체를 합쇼체로
//
// 규칙표다. 모델이 아니라서 아는 말만 바꾼다 — 모르는 말은 건드리지 않고 그대로 둔다.
// 그래야 사용자가 적은 사실이 조용히 바뀌는 일이 없다.

/* ─────────────── ① 군더더기 ─────────────── */

// 문장 첫머리에 붙는 말버릇. 뜻을 담지 않으므로 지운다.
// 한 글자짜리(뭐·음·어·아·그)는 뒤에 쉼표나 공백이 와야 말버릇이다.
// 그러지 않으면 「그래서」의 「그」, 「어떻게」의 「어」까지 먹는다.
const OPENERS = /(?:^|(?<=[.!?]\s))\s*(?:(?:아니(?:요)?|근데|그런데요?|그니까|그러니까|암튼|아무튼|어쨌든|일단|사실|솔직히|개인적으로)(?=[\s,]|$)|(?:뭐|음|어|아|저기|그)(?=\s*,))\s*[,]?\s*/g

// 문장 가운데 끼는 강조·머뭇거림. 앞뒤 공백까지 함께 지운다.
const FILLERS = /\s*(?:막|좀|그냥|진짜|정말로|완전|되게|엄청|약간|살짝|한번|좀만|뭐랄까|이제|또)\s+/g

/* ─────────────── ② 맞춤법 ─────────────── */

const SPELLING = [
  [/색\s*바램/g, '변색'],
  [/바램/g, '바람'],
  [/되요/g, '돼요'],
  [/됬/g, '됐'],
  [/몇일/g, '며칠'],
  [/오랫만/g, '오랜만'],
  [/금새/g, '금세'],
  [/할께/g, '할게'],
  [/갈께/g, '갈게'],
  [/줄께/g, '줄게'],
  [/뵈요/g, '봬요'],
  [/있읍니다/g, '있습니다'],
  [/없읍니다/g, '없습니다'],
  [/어떻해/g, '어떡해'],
  [/왠만/g, '웬만'],
  [/왠일/g, '웬일'],
  [/焉/g, ''],
  [/데로 (?=하|주|가)/g, '대로 '],
  [/안되/g, '안 되'],
  [/안돼/g, '안 돼'],
  [/못하고 있어/g, '못하고 있어'],
  [/([가-힣])구요/g, '$1고요'],       // 더라구요 → 더라고요
  [/([가-힣])던지(?=\s|$|[,.])/g, '$1든지'],
]

/* ─────────────── ③ 말투 ─────────────── */

// 구어 낱말 → 서면 낱말. 사실을 바꾸지 않는 것만 담는다.
const LEXICON = [
  [/카톡/g, '카카오톡 메시지'],
  [/카카오톡 메시지으로/g, '카카오톡 메시지로'],
  [/문자를? 씹|읽고\s*씹|읽씹/g, '메시지를 확인하고도 답하지 않'],
  [/씹었어요|씹더라고요|씹네요/g, '답하지 않았습니다'],
  [/잠수(?:를)?\s*(?:탔어요|탔습니다|타고)/g, '연락이 두절되었습니다'],
  [/튀었어요|먹튀/g, '이행하지 아니하였습니다'],
  [/(\d+)\s*년\s*(?=거주|살)/g, '$1년간 '],
  [/살면서/g, '거주하면서'],
  [/살았어요|살았습니다/g, '거주하였습니다'],
  [/나갈\s*때/g, '퇴거 당시'],
  [/이사\s*나갈\s*때/g, '퇴거 당시'],
  [/찍어\s*뒀|찍어\s*놨/g, '촬영해 두었'],
  [/사진을?\s*찍었/g, '사진을 촬영하였'],
  [/눌린\s*자국/g, '눌림 자국'],
  [/([가-힣]+)\s*낸\s*데는/g, '$1 낸 부분은'],
  [/(?<=[가-힣])\s*데는(?=\s|$)/g, ' 부분은'],
  [/돈을\s*달라고/g, '금원의 지급을'],
  [/돈을\s*빌려/g, '금원을 대여하'],
  [/열쇠(?:를)?\s*넘기고/g, '열쇠를 인도하고'],
  [/다\s*비웠/g, '목적물을 모두 비웠'],
  [/집주인|임대인분/g, '임대인'],
  [/세입자/g, '임차인'],
  [/사장님|대표님/g, '사용자'],
  [/월급/g, '임금'],
  // 구어 조사 — 서면에서는 쓰지 않는다
  [/한테서/g, '으로부터'],
  [/한테/g, '에게'],
  [/(?<=[가-힣])랑(?=\s)/g, '와'],
  [/돈\s*달라고\s*했는데/g, '금원의 지급을 요구하였으나'],
  [/돈\s*달라고/g, '금원의 지급을 요구하며'],
  [/(?<=\s)다\s+(?=[가-힣])/g, '모두 '],
]

/**
 * 나열하는 「~하고」를 「~과/와」로. 「A하고 B뿐이에요」처럼 명사를 잇는 자리만 바꾼다.
 * 동사 뒤의 「~하고」(예: 「전화하고 나서」)는 건드리지 않는다.
 */
function joinNouns(text) {
  return text.replace(/([가-힣]{2,})하고\s+([가-힣]{2,})/g, (m, a, b) => {
    // 「A하다」로 쓰이는 말이면 동사 활용이므로 그대로 둔다
    if (/(?:전화|연락|말|얘기|이야기|생각|계약|약속|신고|청구|요구|제출|인도|지급|변제|반환|퇴거|이사|정리|수리|확인|합의)$/.test(a)) return m
    const last = a.charCodeAt(a.length - 1)
    const hasBatchim = last >= 0xac00 && last <= 0xd7a3 && (last - 0xac00) % 28
    return `${a}${hasBatchim ? '과' : '와'} ${b}`
  })
}

/**
 * 종결어미 → 서면 어미.
 * 긴 것부터 본다 — 「하지 않았어요」가 「았어요」보다 먼저 걸려야 한다.
 */
const ENDINGS = [
  [/하지\s*않았어요$/, '하지 아니하였습니다'],
  [/하지\s*않아요$/, '하지 아니합니다'],
  [/지\s*않았어요$/, '지 아니하였습니다'],
  [/지\s*않아요$/, '지 아니합니다'],
  [/안\s*([가-힣]+)았어요$/, '$1지 아니하였습니다'],
  [/안\s*([가-힣]+)어요$/, '$1지 아니합니다'],
  [/안\s*([가-힣]+)아요$/, '$1지 아니합니다'],
  [/뿐이에요$/, '뿐입니다'],
  [/뿐이었어요$/, '뿐이었습니다'],
  [/거든요$/, '습니다'],
  [/잖아요$/, '습니다'],
  [/더라고요$/, '였습니다'],
  [/(?:네요|군요|는데요|던데요)$/, '습니다'],
  [/했어요$/, '하였습니다'],
  [/였어요$/, '이었습니다'],
  [/봤어요$/, '보았습니다'],
  [/뒀어요$/, '두었습니다'],
  [/왔어요$/, '왔습니다'],
  [/갔어요$/, '갔습니다'],
  [/줬어요$/, '주었습니다'],
  [/받았어요$/, '받았습니다'],
  [/있어요$/, '있습니다'],
  [/없어요$/, '없습니다'],
  [/같아요$/, '것으로 보입니다'],
  [/몰라요$/, '알지 못합니다'],
  // 전해 들은 말 — 「된대요」 → 「된다고 합니다」
  [/([가-힣])ㄴ?대요$/, '$1다고 합니다'],
  [/래요$/, '라고 합니다'],
  // 부탁하는 말투는 서면에서 「구합니다」로 바뀐다
  [/게\s*해\s*주세요$/, '도록 하여 주시기 바랍니다'],
  [/해\s*주세요$/, '하여 주시기 바랍니다'],
  [/주세요$/, '주시기 바랍니다'],
  [/바랍니다만$/, '바랍니다'],
  [/([가-힣])았어요$/, '$1았습니다'],
  [/([가-힣])었어요$/, '$1었습니다'],
  [/해요$/, '합니다'],
  [/이에요$/, '입니다'],
  [/예요$/, '입니다'],
  [/([가-힣])아요$/, '$1습니다'],
  [/([가-힣])어요$/, '$1습니다'],
]

// 줄어든 과거형 → 어간. 「안 줬어요」를 「주지 아니하였습니다」로 만들려면 이게 필요하다.
const CONTRACTED = {
  줬: '주', 왔: '오', 봤: '보', 했: '하', 됐: '되', 갔: '가',
  냈: '내', 썼: '쓰', 샀: '사', 짰: '짜', 켰: '켜', 팠: '파',
}

/** 「안 ~」 부정을 서면 부정으로 — 「안 줬어요」 → 「주지 아니하였습니다」 */
function negate(sentence) {
  return sentence.replace(/안\s*([가-힣])(?:았|었)?어요$/, (m, verb) => {
    const stem = CONTRACTED[verb]
    if (stem) return `${stem}지 아니하였습니다`
    return `${verb}지 아니하였습니다`
  }).replace(/안\s*([가-힣]+)([았었])어요$/, (m, stem) => `${stem}지 아니하였습니다`)
}

/** 이미 서면 어미로 끝나는가 */
const isFormal = (s) => /(?:습니다|입니다|됩니다|합니다|합니다만|봅니다|드립니다)$/.test(s)

/**
 * 한 문장을 서면 문장으로.
 * 아는 어미가 없으면 그대로 둔다 — 억지로 바꾸다 뜻을 비틀면 안 된다.
 */
export function formalSentence(sentence) {
  const s = sentence.trim()
  if (!s) return ''
  if (isFormal(s)) return s
  const negated = negate(s)
  if (negated !== s) return negated
  for (const [pattern, to] of ENDINGS) {
    if (pattern.test(s)) return s.replace(pattern, to)
  }
  return s
}

/**
 * 문장부호·군더더기·맞춤법만 정리한다. 말투는 건드리지 않는다.
 * (구어 그대로 보여줘야 하는 자리에서도 쓸 수 있게 따로 뒀다)
 */
export function tidy(value) {
  let text = String(value || '')
    .normalize('NFC')
    .replace(/\r/g, '')
    .replace(/[ \t]+/g, ' ')
    // 말줄임표·반복 부호 → 온점 하나
    .replace(/[…‥]+/g, '.')
    .replace(/\.{2,}/g, '.')
    .replace(/[!]{1,}/g, '.')
    .replace(/[?]{2,}/g, '?')
    .replace(/~+/g, '')
    .replace(/ㅋ+|ㅎ+|ㅜ+|ㅠ+|ㄷ+ㄷ+/g, '')
    .replace(/(?<!\d)\s*,\s*(?!\d)/g, ', ')

  // 「아니, 근데」처럼 겹쳐 나오면 한 번으로는 안 지워진다
  for (let i = 0; i < 4; i += 1) {
    const before = text
    text = text.replace(OPENERS, '')
    if (text === before) break
  }
  text = text.replace(FILLERS, ' ')
  SPELLING.forEach(([from, to]) => { text = text.replace(from, to) })
  return text.replace(/\s{2,}/g, ' ').replace(/\s+([,.])/g, '$1').trim()
}

/**
 * 평소 말투 → 서면 문장.
 * 문장으로 끊어 각각 다듬고 온점을 붙여 잇는다.
 */
export function formalize(value) {
  let text = tidy(value)
  if (!text) return ''
  // 낱말을 바꾸기 전에 처리한다 — 바꾸고 나면 「인도하고」가 동사인지 알 수 없다
  text = joinNouns(text)
  LEXICON.forEach(([from, to]) => { text = text.replace(from, to) })

  return text
    .split(/\n+|(?<=[.!?])\s+/)
    .map((part) => part.trim().replace(/[.!?]+$/, ''))
    .filter(Boolean)
    .map((part) => `${formalSentence(part)}.`)
    .join(' ')
}
